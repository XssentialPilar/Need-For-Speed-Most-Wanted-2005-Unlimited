param([Parameter(Mandatory=$true)][string]$Fxc)
$ErrorActionPreference='Stop'
$compiled = [IO.Path]::GetTempFileName()
try {
    & $Fxc /nologo /WX /O3 /T ps_3_0 /E MoviePixel9 /Fo $compiled (Join-Path $PSScriptRoot 'movie_reconstruction_d3d9.hlsl')
    if ($LASTEXITCODE) { throw 'Cutscene filter compilation failed.' }
    $bytes = [IO.File]::ReadAllBytes($compiled)
    if ($bytes.Length % 4) { throw 'Invalid shader size.' }
    $words = for ($i=0; $i -lt $bytes.Length; $i+=4) { '0x{0:x8}' -f [BitConverter]::ToUInt32($bytes,$i) }
    $lines = for ($i=0; $i -lt $words.Count; $i+=8) { '    ' + ($words[$i..([Math]::Min($i+7,$words.Count-1))] -join ', ') + ',' }
    $header = @('// Generated by movie_reconstruction_build.ps1.', 'inline constexpr DWORD MoviePixel9[] = {') + $lines + '};'
    [IO.File]::WriteAllText((Join-Path $PSScriptRoot 'movie_reconstruction_d3d9.inc'), ($header -join [char]10) + [char]10, [Text.UTF8Encoding]::new($false))
} finally {
    [IO.File]::Delete($compiled)
}
